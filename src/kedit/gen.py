    ("도움", ["H", "HELP", "?"], "cmd_h"),
    ("새", ["N", "NEW"], "cmd_n"),
    ("복사", ["CP", "COPY"], "cmd_copy"),
    ("붙임", ["PU", "PASTE"], "cmd_paste"),
    ("목록", ["LS", "CAT", "DIR", "LIST"], "cmd_ls"),
    ("정보", ["I"], "cmd_i"),
    ("지움", ["D"], "cmd_d"),
